import AdmZip from 'adm-zip';
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ACCEPTED_PARENT_BRANCH,
  ACCEPTED_PARENT_COMMIT,
  PROTECTED_PACKAGE_LOCK_SHA256,
  RELEASE_DOCUMENTS,
  RELEASE_ID,
  RELEASE_ROOT,
  RUNTIME_FOLDER_NAME,
  RUNTIME_PRODUCTION_SCRIPTS,
  RUNTIME_ZIP_NAME,
  SOURCE_EXCLUDED_PATH_PATTERNS,
  SOURCE_FOLDER_NAME,
  SOURCE_OPERATIONAL_SCRIPTS,
  SOURCE_PRODUCTION_SCRIPTS,
  SOURCE_ROOT_DIRECTORIES,
  SOURCE_ROOT_FILES,
  SOURCE_ZIP_NAME,
} from './production-release-policy.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const outputFlag = args.indexOf('--output');
const requestedOutput =
  outputFlag >= 0 && args[outputFlag + 1] ? args[outputFlag + 1] : RELEASE_ROOT;
const outputRoot = resolve(root, requestedOutput);
const sourceRoot = join(outputRoot, SOURCE_FOLDER_NAME);
const runtimeRoot = join(outputRoot, RUNTIME_FOLDER_NAME);
const sourceZipPath = join(outputRoot, SOURCE_ZIP_NAME);
const runtimeZipPath = join(outputRoot, RUNTIME_ZIP_NAME);

const normalized = (value) => value.split(sep).join('/');
const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');
const sha256File = (file) => sha256(readFileSync(file));

const shouldExcludeSourcePath = (relativePath) => {
  const rel = normalized(relativePath);
  return SOURCE_EXCLUDED_PATH_PATTERNS.some((pattern) => pattern.test(rel));
};

const copyTree = (source, destination, filter) => {
  cpSync(source, destination, {
    recursive: true,
    preserveTimestamps: false,
    filter: (currentSource) => {
      const rel = relative(root, currentSource);
      if (!rel) return true;
      return filter(rel, currentSource);
    },
  });
};

const copyExactFile = (relativePath, destinationRoot = sourceRoot) => {
  const from = join(root, relativePath);
  if (!existsSync(from))
    throw new Error(`Required release input is missing: ${relativePath}`);
  const to = join(destinationRoot, relativePath);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to);
};

const sanitizePackageJson = (scriptNames) => {
  const source = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const scripts = {};
  for (const name of scriptNames) {
    if (!source.scripts?.[name])
      throw new Error(`Required package script is missing: ${name}`);
    scripts[name] = source.scripts[name];
  }
  return {
    ...source,
    scripts,
  };
};

const productVersion = JSON.parse(
  readFileSync(join(root, 'package.json'), 'utf8'),
).version;

const productionReadme = (kind) =>
  `# VoiceCloud Production ${kind}\n\nProduct version: ${productVersion}\nSource commit: ${ACCEPTED_PARENT_COMMIT}\n\nThis package was generated by the repository-controlled VoiceCloud production release pipeline. It intentionally excludes local secrets, runtime uploads, Git metadata, caches, test/acceptance artifacts and engineering-only acceptance history.\n\n## Environment\n\nCopy \`.env.example\` to \`.env\` on the deployment host and replace every \`CHANGE_ME\` value. Never commit the deployment \`.env\`. Keep \`DATABASE_SYNCHRONIZE=false\` and use real PostgreSQL/Redis in production.\n\n## Install\n\n${kind === 'Source' ? '`npm ci`' : '`npm ci --omit=dev`'}\n\n## ${kind === 'Source' ? 'Build and start' : 'Start'}\n\n${kind === 'Source' ? '`npm run build`\n\n`npm run start:prod`' : '`npm run start:prod`'}\n\n## Database\n\nFresh empty database only: \`npm run database:bootstrap:prod\`.\nExisting database: \`npm run migration:status:prod\` then \`npm run migration:run:prod\`.\nNever bootstrap an existing database.\n\n${kind === 'Source' ? '## White-label branding\n\nEdit `shared/branding/index.ts` and replace the four files under `shared/branding/public/brand/`, then rebuild. Do not treat JWT/database/migration/storage identifiers as branding. See `docs/production/WHITE-LABEL-GUIDE.md`.\n' : 'This runtime package is already compiled. White-label identity must be changed in the production source package and rebuilt; do not edit compiled bundles manually.\n'}\n`;

const walkFiles = (directory) => {
  const files = [];
  const walk = (current) => {
    for (const name of readdirSync(current).sort()) {
      const absolute = join(current, name);
      const info = statSync(absolute);
      if (info.isDirectory()) walk(absolute);
      else files.push(absolute);
    }
  };
  walk(directory);
  return files;
};

const writeIntegrityFiles = (packageRoot, kind) => {
  const payloadFiles = walkFiles(packageRoot).filter((file) => {
    const rel = normalized(relative(packageRoot, file));
    return rel !== 'RELEASE-MANIFEST.json' && rel !== 'SHA256SUMS.txt';
  });
  const payload = payloadFiles.map((file) => ({
    path: normalized(relative(packageRoot, file)),
    sha256: sha256File(file),
    bytes: statSync(file).size,
  }));
  const manifest = {
    schemaVersion: 1,
    product: 'VoiceCloud',
    productVersion,
    packageKind: kind,
    sourceCommit: ACCEPTED_PARENT_COMMIT,
    protectedPackageLockSha256: PROTECTED_PACKAGE_LOCK_SHA256,
    deterministic: true,
    payload,
  };
  writeFileSync(
    join(packageRoot, 'RELEASE-MANIFEST.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );

  const checksumFiles = walkFiles(packageRoot).filter(
    (file) => normalized(relative(packageRoot, file)) !== 'SHA256SUMS.txt',
  );
  const checksums = checksumFiles
    .map(
      (file) =>
        `${sha256File(file)}  ${normalized(relative(packageRoot, file))}`,
    )
    .join('\n');
  writeFileSync(join(packageRoot, 'SHA256SUMS.txt'), `${checksums}\n`, 'utf8');
};

const writeDeterministicZip = (folder, zipPath, rootFolderName) => {
  const zip = new AdmZip();
  const fixedDate = new Date(2000, 0, 1, 0, 0, 0);
  for (const file of walkFiles(folder)) {
    const rel = normalized(relative(folder, file));
    const entryName = `${rootFolderName}/${rel}`;
    zip.addFile(entryName, readFileSync(file), '');
    const entry = zip.getEntry(entryName);
    if (entry?.header) {
      entry.header.made = 0x0314;
      entry.header.time = fixedDate;
    }
  }
  zip.writeZip(zipPath);
};

rmSync(outputRoot, { recursive: true, force: true });
mkdirSync(sourceRoot, { recursive: true });
mkdirSync(runtimeRoot, { recursive: true });

for (const file of SOURCE_ROOT_FILES) copyExactFile(file);
for (const directory of SOURCE_ROOT_DIRECTORIES) {
  copyTree(
    join(root, directory),
    join(sourceRoot, directory),
    (rel) => !shouldExcludeSourcePath(rel),
  );
}
for (const script of SOURCE_OPERATIONAL_SCRIPTS) copyExactFile(script);
for (const document of RELEASE_DOCUMENTS) copyExactFile(document);
writeFileSync(
  join(sourceRoot, 'package.json'),
  `${JSON.stringify(sanitizePackageJson(SOURCE_PRODUCTION_SCRIPTS), null, 2)}\n`,
  'utf8',
);
writeFileSync(
  join(sourceRoot, 'README-PRODUCTION.md'),
  productionReadme('Source'),
  'utf8',
);
writeIntegrityFiles(sourceRoot, 'production-source');

if (!existsSync(join(root, 'dist', 'src', 'main.js'))) {
  throw new Error(
    'Runtime package requires a successful unified build. Run "npm run build" first.',
  );
}
copyTree(join(root, 'dist'), join(runtimeRoot, 'dist'), (rel) => {
  const normalizedRel = normalized(rel);
  return (
    !/\.map$/i.test(normalizedRel) && !/\.d\.[cm]?ts$/i.test(normalizedRel)
  );
});
for (const file of ['.env.example', 'package-lock.json'])
  copyExactFile(file, runtimeRoot);
copyExactFile('scripts/start-production.mjs', runtimeRoot);
writeFileSync(
  join(runtimeRoot, 'package.json'),
  `${JSON.stringify(sanitizePackageJson(RUNTIME_PRODUCTION_SCRIPTS), null, 2)}\n`,
  'utf8',
);
writeFileSync(
  join(runtimeRoot, 'README-PRODUCTION.md'),
  productionReadme('Runtime'),
  'utf8',
);
writeIntegrityFiles(runtimeRoot, 'production-runtime');

writeDeterministicZip(sourceRoot, sourceZipPath, SOURCE_FOLDER_NAME);
writeDeterministicZip(runtimeRoot, runtimeZipPath, RUNTIME_FOLDER_NAME);

const releaseIndex = {
  schemaVersion: 1,
  releaseId: RELEASE_ID,
  acceptedParent: {
    branch: ACCEPTED_PARENT_BRANCH,
    commit: ACCEPTED_PARENT_COMMIT,
  },
  artifacts: [
    {
      file: SOURCE_ZIP_NAME,
      sha256: sha256File(sourceZipPath),
      bytes: statSync(sourceZipPath).size,
    },
    {
      file: RUNTIME_ZIP_NAME,
      sha256: sha256File(runtimeZipPath),
      bytes: statSync(runtimeZipPath).size,
    },
  ],
};
writeFileSync(
  join(outputRoot, 'RELEASE-INDEX.json'),
  `${JSON.stringify(releaseIndex, null, 2)}\n`,
  'utf8',
);

console.log('VoiceCloud production release packages generated.');
console.log(`Source folder: ${sourceRoot}`);
console.log(`Runtime folder: ${runtimeRoot}`);
console.log(`Source ZIP: ${sourceZipPath}`);
console.log(`Runtime ZIP: ${runtimeZipPath}`);
console.log(`Release index: ${join(outputRoot, 'RELEASE-INDEX.json')}`);
